// Support ultimates used in roster compatibility checks (src/types/roster.ts SupportUltimate).
// Ability IDs from src/types/abilities.ts (KnownAbilities).
// prettier-ignore
const SUPPORT_ULTIMATE_MAP = new Map<number, string>([
  [40223, 'Aggressive Warhorn'],
  [122388, 'Glacial Colossus'],
  [40237, 'Barrier'],       // Reviving Barrier
  [40239, 'Barrier'],       // Replenishing Barrier
  [23495, 'Greater Storm Atronach'],
]);

export interface CompactSkills {
  l1?: number | string;
  l2?: number | string;
  l3?: number | string;
}

export interface TalentDetectionResult {
  sl?: CompactSkills;
  ul?: string;
}

/**
 * Detect class skill lines, ultimate, and specific skills from ESO Logs talents.
 *
 * Returns compact-roster-compatible fields ready to spread into a CompactTank/Healer/DPS.
 */
export function detectTalentInfo(talents: TalentItem[]): TalentDetectionResult {
  if (!talents?.length) return {};

  const lineCounts = new Map<number, number>();
  let ultimateName: string | undefined;

  for (const talent of talents) {
    const guid = talent.guid;
    if (typeof guid !== 'number') continue;

    // Support ultimates take priority over class ultimates
    const supportUlt = SUPPORT_ULTIMATE_MAP.get(guid);
    if (supportUlt && !ultimateName) {
      ultimateName = supportUlt;
    }

    const lineIdx = ABILITY_TO_LINE.get(guid);
    if (lineIdx === undefined) continue;

    lineCounts.set(lineIdx, (lineCounts.get(lineIdx) ?? 0) + 1);
  }

  const result: TalentDetectionResult = {};

  // Top 3 skill lines by ability count → encode as CLASS_SKILL_LINES indices
  const topLines = [...lineCounts.entries()].sort((a, b) => b[1] - a[1]).slice(0, 3);

  if (topLines.length > 0) {
    const sl: CompactSkills = {};
    if (topLines[0]) sl.l1 = topLines[0][0];
    if (topLines[1]) sl.l2 = topLines[1][0];
    if (topLines[2]) sl.l3 = topLines[2][0];
    result.sl = sl;
  }

  if (ultimateName) {
    result.ul = ultimateName;
  }

  return result;
}
