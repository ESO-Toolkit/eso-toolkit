/**
 * One-time backfill — derive each existing build's `visibility` column from the
 * visibility already embedded in its encoded `build_data` blob.
 *
 * Why: migration-build-visibility.sql adds `visibility TEXT NOT NULL DEFAULT
 * 'public'`, which backfills EVERY pre-existing row as public. But builds
 * encoded before the server column existed may carry settings.visibility =
 * private / link-only inside build_data (the `vs` field). Without this backfill
 * those builds would be authoritatively published as public and become
 * listable/fetchable by non-owners — a privacy regression. Run this right after
 * the ALTER, before the new visibility checks go live.
 *
 * Usage (export rows → derive UPDATEs → apply):
 *   wrangler d1 execute roster-hub-db --remote --json \
 *     --command "SELECT id, build_data FROM builds" > builds-export.json
 *   node roster-hub-api/src/db/backfill-visibility.mjs builds-export.json \
 *     > roster-hub-api/src/db/backfill-visibility.sql
 *   wrangler d1 execute roster-hub-db --remote \
 *     --file=roster-hub-api/src/db/backfill-visibility.sql
 *
 * Rows whose blob can't be decoded are left untouched (they keep the migration
 * default of 'public') and reported on stderr so they can be inspected — we do
 * not silently flip an undecodable row.
 *
 * `vs` index mirrors VISIBILITIES in src/utils/buildEncoding.ts:
 *   0 = public (omitted in blob), 1 = private, 2 = link-only
 */
import { readFileSync } from 'node:fs';
import { inflateRawSync } from 'node:zlib';

const VISIBILITIES = ['public', 'private', 'link-only'];

function fromBase64Url(s) {
  const b64 = s.replace(/-/g, '+').replace(/_/g, '/');
  return Buffer.from(b64, 'base64');
}

/** Decode the compact build blob and return its embedded visibility. */
function visibilityFromBuildData(buildData) {
  const bytes = fromBase64Url(buildData);
  const json = inflateRawSync(bytes).toString('utf8');
  const compact = JSON.parse(json);
  // `vs` omitted ⇒ public (the encoder drops 0). Unknown index ⇒ public.
  const idx = typeof compact.vs === 'number' ? compact.vs : 0;
  return VISIBILITIES[idx] ?? 'public';
}

function main() {
  const inputPath = process.argv[2];
  if (!inputPath) {
    console.error('Usage: node backfill-visibility.mjs <builds-export.json>');
    process.exit(1);
  }

  const raw = JSON.parse(readFileSync(inputPath, 'utf8'));
  // wrangler --json wraps results as [{ results: [...] }]; also accept a bare array.
  const rows = Array.isArray(raw) ? (raw[0]?.results ?? raw) : (raw.results ?? []);

  let updates = 0;
  let skipped = 0;
  const lines = [
    '-- Generated by backfill-visibility.mjs — derives visibility from build_data',
    '',
  ];

  for (const row of rows) {
    if (!row?.id || typeof row.build_data !== 'string') {
      skipped++;
      continue;
    }
    let visibility;
    try {
      visibility = visibilityFromBuildData(row.build_data);
    } catch (err) {
      console.error(`skip ${row.id}: could not decode build_data (${err.message})`);
      skipped++;
      continue;
    }
    // Only emit a change where the derived value differs from the migration
    // default; public rows are already correct.
    if (visibility !== 'public') {
      const safeId = String(row.id).replace(/'/g, "''");
      lines.push(`UPDATE builds SET visibility = '${visibility}' WHERE id = '${safeId}';`);
      updates++;
    }
  }

  process.stdout.write(lines.join('\n') + '\n');
  console.error(`backfill: ${updates} non-public update(s), ${skipped} row(s) skipped.`);
}

main();
