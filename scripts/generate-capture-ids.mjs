#!/usr/bin/env node
/**
 * generate-capture-ids.mjs
 *
 * Builds the explicit ability-ID list the addon captures via its ID-driven pass
 * (tools/eso-tooltip-dump/CaptureIds.lua). The skill-tree walk only enumerates
 * abilities the character can see in the tree; progression-gated abilities
 * (notably SCRIBING grimoires/morphs) are never walked. This list lets the addon
 * call GetAbilityDescription directly for those IDs.
 *
 * Sources:
 *   - data/scribing-complete.json  → every grimoire id + transformation abilityId
 *   - src/data/skill-lines/ability-ids.ts → the AbilityId enum (safety net for any
 *     app-referenced ability the tree walk might miss)
 *
 * Output: tools/eso-tooltip-dump/CaptureIds.lua (a Lua table of numeric ids).
 *
 * Usage: node scripts/generate-capture-ids.mjs
 */

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const ids = new Set();
const addBig = (v) => {
  if (typeof v === 'number' && Number.isFinite(v) && v > 10000) ids.add(v);
};

// --- scribing ids ---------------------------------------------------------
const scribing = JSON.parse(
  fs.readFileSync(path.join(ROOT, 'data/scribing-complete.json'), 'utf8'),
);
const grimoires = Array.isArray(scribing.grimoires)
  ? scribing.grimoires
  : Object.values(scribing.grimoires || {});
let scribingCount = 0;
for (const g of grimoires) {
  const before = ids.size;
  addBig(g.id);
  for (const t of Object.values(g.nameTransformations || {})) {
    for (const aid of t.abilityIds || []) addBig(aid);
  }
  scribingCount += ids.size - before;
}
for (const key of ['focusScripts', 'signatureScripts', 'affixScripts']) {
  const coll = scribing[key];
  const arr = Array.isArray(coll) ? coll : Object.values(coll || {});
  for (const x of arr) {
    addBig(x?.id);
    for (const aid of x?.abilityIds || []) addBig(aid);
  }
}
const afterScribing = ids.size;

// --- AbilityId enum (safety net) -----------------------------------------
const enumTxt = fs.readFileSync(
  path.join(ROOT, 'src/data/skill-lines/ability-ids.ts'),
  'utf8',
);
let m;
const re = /=\s*(\d+)/g;
while ((m = re.exec(enumTxt))) addBig(Number(m[1]));

const list = [...ids].sort((a, b) => a - b);

// --- emit Lua -------------------------------------------------------------
const lines = [];
lines.push('-- CaptureIds.lua — GENERATED by scripts/generate-capture-ids.mjs. Do not edit by hand.');
lines.push('-- Explicit ability ids for the addon ID-driven capture pass (scribing + AbilityId enum).');
lines.push('-- These supplement the skill-tree walk, which cannot enumerate progression-gated abilities.');
lines.push('ESOTooltipDumpCaptureIds = {');
// 12 ids per line for readability
for (let i = 0; i < list.length; i += 12) {
  lines.push('  ' + list.slice(i, i + 12).join(', ') + ',');
}
lines.push('}');
lines.push('');

const out = path.join(ROOT, 'tools/eso-tooltip-dump/CaptureIds.lua');
fs.writeFileSync(out, lines.join('\n'));

console.log(`Wrote ${path.relative(ROOT, out)}`);
console.log(`  total ids:      ${list.length}`);
console.log(`  from scribing:  ${afterScribing}`);
console.log(`  range:          ${list[0]} .. ${list[list.length - 1]}`);
